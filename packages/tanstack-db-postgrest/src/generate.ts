// Node-side: reads the database catalog through `@tspg/introspect` (inlined into the build) and writes
// the module a browser bundle imports. Nothing here reaches the client.
import { columnType, introspect, tsKey } from "@tspg/introspect";
import type { DbSession, Relation, SchemaCache } from "@tspg/introspect";

/** Where the catalog comes from: one already read, or a database session to read it from. */
export type GenerateSource = SchemaCache | { readonly db: DbSession; readonly schemas?: ReadonlyArray<string> };

export interface GenerateOptions {
  /** Name of the exported `Database` type. Default `"Database"`. */
  readonly name?: string;
  /** Name of the exported keys constant. Default `"keys"`. */
  readonly keysName?: string;
  /** Banner comment. `false` leaves it out. */
  readonly header?: string | false;
}

const read = (c: string): string => `row${/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(c) ? `.${c}` : `[${JSON.stringify(c)}]`}`;

const isCache = (s: GenerateSource): s is SchemaCache => "relations" in s;

const shape = (rel: Relation, rows: "row" | "insert"): string => {
  const fields = rel.columns
    // a column the database refuses a value for (a stored generated one, an `ALWAYS` identity) cannot be inserted,
    // unless it is the primary key, which the client still holds the optimistic row by
    .filter((c) => !(rows === "insert" && (c.generated || c.identity === "always") && !rel.pk.includes(c.name)))
    .map((c) => {
      const t = `${columnType(c)}${c.nullable ? " | null" : ""}`;
      // On the way in, a column the database fills (a default) or accepts NULL for may be left out -- except the
      // primary key: a client that keeps rows by key needs one at once, for the optimistic row.
      const optional = rows === "insert" && !rel.pk.includes(c.name) && (c.hasDefault || c.nullable);
      return `${tsKey(c.name)}${optional ? "?" : ""}: ${t}`;
    });
  return `{ ${fields.join("; ")} }`;
};

/**
 * The module a TanStack DB client needs, as text: a `Database` type of the tables and views (row and
 * insert shapes, primary key, whether each can be written) and `keys`, the code that turns a row into
 * its collection key -- the value for one key column, the values joined with `_` for several (`12_3`).
 *
 * It imports nothing, so a browser bundle takes the type with `import type` and `keys` is a few
 * functions. Pass both to `tspgClient<Database>({ keys })`. Regenerate after a migration.
 *
 * ```ts ignore
 * import { generate } from "@tspg/tanstack-db-postgrest/generate";
 * import { nodePostgresAdapter } from "@tspg/introspect/adapters/node-postgres";
 * writeFileSync("src/db.ts", await generate({ db: nodePostgresAdapter(pool), schemas: ["api"] }));
 * ```
 *
 * A composite-type column is typed `unknown`: the client takes what the API sends.
 */
export const generate = async (source: GenerateSource, options: GenerateOptions = {}): Promise<string> => {
  const cache = isCache(source) ? source : await introspect(source);
  const name = options.name ?? "Database";
  const keysName = options.keysName ?? "keys";
  const header =
    options.header === false
      ? ""
      : `${options.header ?? "// Generated by @tspg/tanstack-db-postgrest -- do not edit. Regenerate after a migration."}\n\n`;
  const schemas = [...cache.schemas];
  const relationsOf = (schema: string) =>
    [...cache.relations.values()].filter((r) => r.schema === schema).sort((a, b) => a.name.localeCompare(b.name));
  const first = JSON.stringify(schemas[0] ?? "");

  const type: string[] = [`export type ${name} = {`, `  default: ${first};`, "  schemas: {"];
  const keys: string[] = [`export const ${keysName} = {`, `  default: ${first},`, "  schemas: {"];
  for (const schema of schemas) {
    type.push(`    ${tsKey(schema)}: {`);
    keys.push(`    ${tsKey(schema)}: {`);
    for (const rel of relationsOf(schema)) {
      type.push(
        `      ${tsKey(rel.name)}: {`,
        `        row: ${shape(rel, "row")};`,
        `        insert: ${shape(rel, "insert")};`,
        `        pk: [${rel.pk.map((c) => JSON.stringify(c)).join(", ")}];`,
        `        insertable: ${rel.insertable};`,
        `        updatable: ${rel.updatable};`,
        `        deletable: ${rel.deletable};`,
        "      };",
      );
      if (rel.pk.length === 0) continue; // a view: no key to build, the collection names its columns
      const byName = new Map(rel.columns.map((c) => [c.name, c]));
      const typeOf = (c: string) => columnType(byName.get(c) ?? { type: "unknown" });
      const params = rel.pk.map((c) => `${tsKey(c)}: ${typeOf(c)}`).join("; ");
      // key columns the database makes up (an identity, a sequence): what the client holds the optimistic row by is a
      // placeholder for them, and is kept out of the POST. A key the client can make itself (a uuid) is sent.
      const made = rel.pk.filter((c) => {
        const col = byName.get(c);
        return col?.identity !== undefined || /^nextval\(/i.test(col?.defaultExpr ?? "");
      });
      const only = rel.pk.length === 1 ? rel.pk[0]! : undefined;
      // Keep this in step with `compositeKey` of this package: one column is its value (a number or a
      // string stays as it is), several are their `String()` joined with `_`, in the order of the key.
      const body =
        only === undefined
          ? `\`${rel.pk.map((c) => `\${${read(c)}}`).join("_")}\``
          : /^(number|string)$/.test(typeOf(only))
            ? read(only)
            : `String(${read(only)})`;
      keys.push(
        `      ${tsKey(rel.name)}: {`,
        `        pk: [${rel.pk.map((c) => JSON.stringify(c)).join(", ")}],`,
        `        generated: [${made.map((c) => JSON.stringify(c)).join(", ")}],`,
        `        key: (row: { ${params} }) => ${body},`,
        "      },",
      );
    }
    type.push("    };");
    keys.push("    },");
  }
  type.push("  };", "};");
  keys.push("  },", "} as const;");
  return `${header}${type.join("\n")}\n\n${keys.join("\n")}\n`;
};
