// The real thing: a TanStack DB collection against `@tspg/rest` (createRest) on PGlite, Postgres
// in-process, so the PostgREST wire format is exercised rather than assumed.
import { afterAll, beforeAll, expect, test } from "bun:test";
import { PGlite } from "@electric-sql/pglite";
import { QueryClient } from "@tanstack/query-core";
import {
  and,
  createCollection,
  createLiveQueryCollection,
  eq,
  gt,
  ilike,
  inArray,
  isNull,
  length,
  lower,
  not,
  or,
} from "@tanstack/db";
import { createRest, type RestInstance } from "../../rest/src/index";
import { pgliteAdapter } from "../../adapters/src/pglite";
import { tspgCollectionOptions, TspgRestError } from "../src/index";

type Item = { id: number; name: string; qty: number | null; active: boolean };

let db: PGlite;
let rest: RestInstance;

beforeAll(async () => {
  db = new PGlite();
  await db.exec(`
    DO $$ BEGIN
      IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'anon') THEN CREATE ROLE anon NOLOGIN; END IF;
    END $$;
    GRANT anon TO CURRENT_USER;
    CREATE SCHEMA api;
    GRANT USAGE ON SCHEMA api TO anon;
    CREATE TABLE api.items (
      id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
      name text NOT NULL,
      qty int,
      active boolean NOT NULL DEFAULT true
    );
    GRANT ALL ON api.items TO anon;
    INSERT INTO api.items (name, qty, active) VALUES
      ('apple', 5, true), ('Banana', 0, true), ('cherry', NULL, false), ('50%_off', 7, true), ('date', 12, false);
  `);
  rest = await createRest({ db: pgliteAdapter(db), schemas: ["api"], anonymousRole: "anon" });
});

afterAll(async () => {
  await rest.close();
  await db.close();
});

function items() {
  return createCollection(
    tspgCollectionOptions<Item>({
      url: "http://test",
      table: "items",
      omitOnInsert: ["id"],
      queryClient: new QueryClient(),
      fetch: ((url: string, init?: RequestInit) => rest.handle(new Request(url, init))) as typeof fetch,
    }),
  );
}

/** What the live query yields, ordered by id, for a `where` the server may or may not understand. */
async function ids(where: (r: any) => any): Promise<number[]> {
  const c = items();
  const live = createLiveQueryCollection((q) =>
    q
      .from({ i: c })
      .where(({ i }) => where(i))
      .orderBy(({ i }) => i.id),
  );
  await live.preload();
  return live.toArray.map((r) => r.id);
}

test("every operator returns what the same filter returns in memory", async () => {
  expect(await ids((i) => and(eq(i.active, true), gt(i.qty, 0)))).toEqual([1, 4]);
  expect(await ids((i) => inArray(i.id, [1, 3, 5]))).toEqual([1, 3, 5]);
  expect(await ids((i) => or(eq(i.name, "date"), gt(i.qty, 6)))).toEqual([4, 5]);
  expect(await ids((i) => not(eq(i.active, true)))).toEqual([3, 5]);
  expect(await ids((i) => not(eq(i.qty, 5)))).toEqual([2, 4, 5]); // NULL is unknown, in SQL and in TanStack DB
  expect(await ids((i) => isNull(i.qty))).toEqual([3]);
  expect(await ids((i) => eq(i.qty, null))).toEqual([]); // `= NULL` is unknown, as in SQL
  expect(await ids((i) => ilike(i.name, "%AN%"))).toEqual([2]);
  expect(await ids((i) => eq(lower(i.name), "banana"))).toEqual([2]);
  expect(await ids((i) => eq(lower(i.name), "50%_off"))).toEqual([4]); // % and _ are literal
  expect(await ids((i) => gt(length(i.name), 5))).toEqual([2, 3, 4]); // not expressible: local filter
});

test("insert, update and delete round-trip through PostgREST syntax", async () => {
  const c = items();
  await createLiveQueryCollection((q) => q.from({ i: c })).preload();
  // The key is generated by the database: the optimistic row's id is replaced by the refetch.
  await c.insert({ id: -1, name: "elder", qty: 1, active: true }).when("settled");
  const { rows } = await db.query<{ id: number; name: string }>("SELECT id, name FROM api.items WHERE name = 'elder'");
  expect(rows).toHaveLength(1);
  const id = rows[0]!.id;

  await c
    .update(id, (d) => {
      d.qty = 42;
    })
    .when("settled");
  expect((await db.query<{ qty: number }>("SELECT qty FROM api.items WHERE id = $1", [id])).rows[0]!.qty).toBe(42);

  await c.delete(id).when("settled");
  expect((await db.query("SELECT 1 FROM api.items WHERE id = $1", [id])).rows).toHaveLength(0);
});

test("a PostgREST error becomes a TspgRestError", async () => {
  const c = createCollection(
    tspgCollectionOptions<Item>({
      url: "http://test",
      table: "nope",
      queryClient: new QueryClient(),
      fetch: ((url: string, init?: RequestInit) => rest.handle(new Request(url, init))) as typeof fetch,
    }),
  );
  await createLiveQueryCollection((q) => q.from({ i: c }))
    .preload()
    .catch(() => {});
  const err = await c.utils.refetch({ throwOnError: true }).then(
    () => undefined,
    (e: unknown) => e,
  );
  expect(err).toBeInstanceOf(TspgRestError);
  expect(err).toMatchObject({ status: 404, code: "PGRST205" });
});

test("eager mode against createRest: the whole table, filtered in memory", async () => {
  const c = createCollection(
    tspgCollectionOptions<Item>({
      url: "http://test",
      table: "items",
      queryClient: new QueryClient(),
      syncMode: "eager",
      fetch: ((url: string, init?: RequestInit) => rest.handle(new Request(url, init))) as typeof fetch,
    }),
  );
  await c.preload();
  expect(c.size).toBeGreaterThanOrEqual(5);
  const live = createLiveQueryCollection((q) => q.from({ i: c }).where(({ i }) => gt(i.qty, 6)));
  await live.preload();
  expect(live.toArray.map((r) => r.name).sort()).toEqual(["50%_off", "date"]);
});
