import { afterAll, beforeAll, expect, test } from "bun:test";
import { PGlite } from "@electric-sql/pglite";
import { pgliteAdapter } from "../../adapters/src/pglite";
import { generate } from "../src/generate";
import { compositeKey } from "../src/postgrest";

let pg: PGlite;
let out: string;
let keys: Record<string, any>;

beforeAll(async () => {
  pg = new PGlite();
  await pg.exec(`
    CREATE SCHEMA api;
    CREATE TABLE api.todos (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, title text NOT NULL, done boolean DEFAULT false, note text);
    CREATE TABLE api.flags (active boolean PRIMARY KEY);
    CREATE TABLE api.order_items (order_id int NOT NULL, product_id uuid NOT NULL, qty int NOT NULL, PRIMARY KEY (order_id, product_id));
    CREATE TABLE api."odd table" ("odd col" int NOT NULL, ok int NOT NULL, PRIMARY KEY ("odd col", ok));
    CREATE VIEW api.totals AS SELECT order_id, sum(qty)::int AS total FROM api.order_items GROUP BY order_id;
  `);
  out = await generate({ db: pgliteAdapter(pg), schemas: ["api"] });
  const js = new Bun.Transpiler({ loader: "ts" }).transformSync(out);
  keys = (await import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`)).keys;
});

afterAll(() => pg.close());

test("the Database type: row, insert and update shapes, key and writability", () => {
  expect(out).toStartWith("// Generated by @tspg/tanstack-db");
  expect(out).toContain("export type Database = {");
  expect(out).toContain('default: "api";');
  expect(out).toContain("row: { id: number; title: string; done: boolean | null; note: string | null };");
  // the identity column, the defaulted one and the nullable one may be left out of an insert
  expect(out).toContain("insert: { id?: number; title: string; done?: boolean | null; note?: string | null };");
  expect(out).toContain('pk: ["order_id", "product_id"];');
  expect(out).toContain("pk: [];\n        insertable: false;"); // a view
});

test("keys: one column is its value, several are joined with `_`", () => {
  const rels = keys.schemas.api;
  expect(keys.default).toBe("api");
  expect(rels.todos.key({ id: 7 })).toBe(7);
  expect(rels.flags.key({ active: true })).toBe("true");
  expect(rels.order_items.key({ order_id: 12, product_id: "p-3" })).toBe("12_p-3");
  expect(rels["odd table"].key({ "odd col": 1, ok: 2 })).toBe("1_2");
  expect(rels.totals).toBeUndefined(); // a view has no key to build
});

test("the generated key is what `compositeKey` builds", () => {
  const rels = keys.schemas.api;
  const rows: Record<string, Record<string, unknown>> = {
    todos: { id: 7 },
    flags: { active: false },
    order_items: { order_id: 12, product_id: "p-3" },
    "odd table": { "odd col": 1, ok: 2 },
  };
  for (const [table, row] of Object.entries(rows)) {
    expect(rels[table].key(row)).toBe(compositeKey(rels[table].pk, row));
  }
});

test("a catalog already read is taken as it is, and the names and header are options", async () => {
  const mod = await generate(
    { db: pgliteAdapter(pg), schemas: ["api"] },
    { name: "Db", keysName: "pks", header: "// mine" },
  );
  expect(mod).toStartWith("// mine");
  expect(mod).toContain("export type Db = {");
  expect(mod).toContain("export const pks = {");
  expect(mod).not.toContain("import ");
  expect(await generate({ db: pgliteAdapter(pg), schemas: ["api"] }, { header: false })).toStartWith("export type");
});
